    <h1>Política de Privacidade</h1>
    <p><strong>Última atualização:</strong> 17 de julho de 2025</p>

    <p>Esta Política de Privacidade descreve como coletamos, usamos e protegemos suas informações pessoais no sistema
        <strong>Nota Premiada de Cacequi</strong>, de responsabilidade da Prefeitura Municipal de Cacequi.</p>

    <h2>1. Coleta de Informações</h2>
    <p>Ao se cadastrar e utilizar o sistema Nota Premiada, poderemos coletar as seguintes informações:</p>
    <ul>
        <li>Nome completo</li>
        <li>CPF</li>
        <li>Telefone e e-mail</li>
        <li>Endereço</li>
        <li>Notas fiscais eletrônicas e cupons cadastrados</li>
        <li>Dados de acesso (data, hora, IP, dispositivo)</li>
    </ul>

    <h2>2. Uso das Informações</h2>
    <p>As informações coletadas são utilizadas para:</p>
    <ul>
        <li>Gerenciar sua participação na campanha Nota Premiada;</li>
        <li>Validar cupons e notas fiscais;</li>
        <li>Entrar em contato com os participantes vencedores;</li>
        <li>Enviar notificações e informações relevantes sobre a campanha;</li>
        <li>Garantir a segurança e autenticidade dos dados;</li>
        <li>Atender exigências legais e regulamentares.</li>
    </ul>

    <h2>3. Compartilhamento de Dados</h2>
    <p>Seus dados poderão ser compartilhados apenas com:</p>
    <ul>
        <li>Órgãos públicos e autoridades competentes, mediante obrigação legal;</li>
        <li>Empresa desenvolvedora e gestora do sistema, sob cláusula de confidencialidade;</li>
        <li>Prestadores de serviço contratados exclusivamente para operação da campanha.</li>
    </ul>

    <h2>4. Segurança</h2>
    <p>Adotamos medidas técnicas e organizacionais adequadas para proteger suas informações pessoais contra acesso não
        autorizado, perda, uso indevido, alteração ou divulgação indevida.</p>

    <h2>5. Retenção de Dados</h2>
    <p>Seus dados serão armazenados enquanto durar a campanha e por tempo necessário para cumprimento de obrigações
        legais ou regulatórias.</p>

    <h2>6. Seus Direitos</h2>
    <p>Você tem o direito de:</p>
    <ul>
        <li>Acessar e corrigir seus dados;</li>
        <li>Solicitar exclusão dos seus dados, quando aplicável;</li>
        <li>Revogar o consentimento, quando o tratamento for baseado nele;</li>
        <li>Obter informações sobre o uso dos seus dados.</li>
    </ul>
    <p>Para exercer seus direitos, entre em contato pelo e-mail: <a
            href="mailto:contato@cacequi.rs.gov.br">contato@cacequi.rs.gov.br</a>.</p>

    <h2>7. Alterações nesta Política</h2>
    <p>Esta Política poderá ser atualizada a qualquer momento. Recomendamos a leitura periódica para se manter informado
        sobre eventuais alterações.</p>

    <h2>8. Contato</h2>
    <p>Em caso de dúvidas ou solicitações relacionadas à privacidade de dados, entre em contato com a Prefeitura de
        Cacequi:</p>
    <ul>
        <li><strong>Telefone:</strong> (55) 3254-2200</li>
        <li><strong>E-mail:</strong> <a href="mailto:contato@cacequi.rs.gov.br">contato@cacequi.rs.gov.br</a></li>
        <li><strong>Endereço:</strong> R. Bento Gonçalves, 363 - Cacequi, RS</li>
    </ul>

    <p><em>Ao utilizar o sistema Nota Premiada, você concorda com os termos desta Política de Privacidade.</em></p>

